print(10/3) # division always returns a float value
print(10//3) # floor division returns the whole number part of the division result, which is 3
print(10%3) # modulus operator returns the remainder of the division, which is 1
print(10**3) # exponentiation operator returns 10 raised to the power of 3, which is 1000   
print(10 + 3) # addition operator returns the sum of 10 and 3, which is 13
print(10 - 3) # subtraction operator returns the difference of 10 and 3, which is 7
print(10 * 3) # multiplication operator returns the product of 10 and 3, which is 30
print(10 / 3) # division operator returns the quotient of 10 and 3, which is 3.333...


x = 10
