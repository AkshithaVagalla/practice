#we use while loops when we want to repeat a block of code until a certain condition is met.
#for example, we want to print numbers from 1 to 10 using a while loop


i = 1
while i < 5 :
    print(i)
    i = i+1
print("Done")




i = 1
while i < 5 :
    print("*" * i) # this will print * i times, so when i is 1, it will print *, when i is 2, it will print **, and so on.
    i = i+1
print("Done")


